fn trap_or_value(wasm: &[u8]) -> String {
    let engine = Engine::default();
    let module = WtModule::new(&engine, wasm).expect("load");
    let mut store = Store::new(&engine, ());
    let instance = Instance::new(&mut store, &module, &[]).expect("instantiate");
    let f = instance.get_func(&mut store, "f").expect("export f");
    let mut out = [Val::I32(0)];
    match f.call(&mut store, &[Val::I32(1)], &mut out) {
        Ok(()) => format!("{:?}", out[0]),
        Err(_) => "trap".to_string(),
    }
}

#[test]
fn invalid_input_is_refused() {
    let input = INVALID_TRAILING_OPERATORS;
    assert!(wasmparser::validate(input).is_err(), "fixture is invalid");
    assert!(parse::parse_wasm(input).is_err());
}

#[test]
fn unreachable_in_a_loop_optimizes_to_valid_equivalent_output() {
    let input = UNREACHABLE_IN_LOOP;
    wasmparser::validate(input).expect("fixture is valid");
    let mut module = parse::parse_wasm(input).expect("parse");
    optimize::optimize_module(&mut module).expect("optimize");
    let out = encode::encode_wasm(&module).expect("encode");
    wasmparser::validate(&out).expect("output validates");
    assert_eq!(trap_or_value(&out), trap_or_value(input));
}
